#include "led.h"

void led_begin() {
    pinMode(LED, OUTPUT);
    digitalWrite(LED, LOW);
}

// ═══════════════════════════════════════════════════════════
// ПРЯМИЙ СЕТТЕР (Заняття 16).
// Приймає голе "on"/"off" — без JSON, без лапок.
// Потрібен тіні: там значення вже витягнуте парсером, і ганяти
// його назад у JSON, щоб знову розібрати рядком, було б безглуздо.
//
// ВАЖЛИВО, що саме означає цей світлодіод після появи Deep Sleep.
// Це вже НЕ актуатор. Сон знеструмлює GPIO — «увімкнене світло»
// між пробудженнями фізично неможливе. Тепер він показує інше:
// пристрій ЗАРАЗ активний. Спалахнув — прокинувся, згас — заснув.
// У Wokwi це найпростіший спосіб побачити вікно активності очима.
// ═══════════════════════════════════════════════════════════
void led_set(const char* state) {
    bool on = (strcmp(state, "on") == 0);

    digitalWrite(LED, on ? HIGH : LOW);

    Serial.print("[LED] Індикація: ");
    Serial.println(on ? "увімкнено" : "вимкнено");
}

// ═══════════════════════════════════════════════════════════
// КОМАНДА З ТОПІКА (Заняття 14).
// Прилітає сирий JSON, тому розбираємо рядком.
// ═══════════════════════════════════════════════════════════
void led_handle_command(const char* cmd) {
    Serial.print("[CMD] Отримано: ");
    Serial.println(cmd);

    // Шукаємо саме значення в лапках, а не пару "ключ":"значення" —
    // тоді пробіли після двокрапки не мають значення.
    // "on" не збігається всередині "off": лапки роблять токени різними
    if (strstr(cmd, "\"on\"") != NULL) {
        led_set("on");

    } else if (strstr(cmd, "\"off\"") != NULL) {
        led_set("off");

    } else {
        Serial.println("[CMD] Невідома команда — ігноруємо");
    }
}